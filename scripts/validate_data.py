"""Validate the curriculum CSVs in data/ against docs/SCHEMA.md and report coverage.

Usage (standard library only):
  python scripts/validate_data.py [data_dir] [--quiet]     (default: data)

Checks: required columns; unique IDs; confidence values; Lao-only text fields;
foreign keys; syllables join back to the word; tone names and counts; spaced
sentences match unspaced ones and their sentence_words; 2+ sentences per word;
the word hard cap (HARD_CAP); letter/vowel coverage by word 600; noun classifiers.
Missing tables are reported and skipped. Exit code 1 if any ERROR.

Revision 2 (2026-10-10):
  - Classifier columns (SCHEMA.md "Classifiers"): classifier_type specific|self|measure|none is
    required on nouns and forbidden on other rows; classifier_confidence is required with it;
    self must point to the row itself, none must have no classifier word, specific needs one
    (warning while the classifier word is still missing from words.csv). Before the column
    exists, a single warning replaces the per-noun warnings.
  - --quiet groups warnings by kind and prints a count with up to 5 examples per kind.
Revision 3 (2026-10-10): ID formats are enforced: word_id W + 6 digits, sentence_id S + 9 digits.
Revision 4 (2026-10-10): word hard cap raised to 3000 (user decision; CLAUDE.md "Targets").
Revision 5 (2026-11-10, PLAN S7c): activity data (DESIGN "Fill in the blank: one logical choice").
  - categories.csv (category, definition, examples): the closed set; names are lower case [a-z_];
    `function` and `action` are expected. Not a DB table.
  - word_categories.csv (word_id, categories, source, confidence, notes): word exists; categories is a
    non-empty pipe list from categories.csv.
  - sentence_slots.csv (sentence_id, position, accepts, exclude_word_ids, source, confidence, notes): the
    sentence has a word at that position (sentence_words); accepts is a non-empty pipe list from
    categories.csv; exclude_word_ids exist; the answer word has a word_categories row and shares a category
    with accepts (a particle's slot lists `function`: function words may be blanked since S7h, never options).
  - word_units.csv (generated by build_order.py): word exists, unit_id set.
  Rows in word_categories / sentence_slots without a categories.csv are an ERROR.
"""
import argparse
import csv
import os
import re
import sys

COMMON = ["source", "confidence", "notes"]
TABLES = {
    "letters": ("letter_id", ["letter_id", "lao", "kind", "consonant_class", "respelling", "coverage_required", "intro_word_id"]),
    "vowels": ("vowel_id", ["vowel_id", "lao_pattern", "length", "ipa", "respelling", "coverage_required", "intro_word_id"]),
    "words": ("word_id", ["word_id", "lao", "ipa", "respelling", "syllables", "tone_by_syllable", "tone_derivation",
                          "pos", "classifier_word_id", "component_word_ids", "gloss_en", "freq_rank", "tier",
                          "intro_order", "new_letter_ids", "new_vowel_ids", "pron_tip"]),
    "sentences": ("sentence_id", ["sentence_id", "lao", "lao_spaced", "ipa", "respelling", "english", "target_word_id", "template_id"]),
    "sentence_words": (None, ["sentence_id", "position", "word_id"]),
    "templates": ("template_id", ["template_id", "lao_pattern", "english_pattern", "slot_names", "intro_order"]),
    "template_fillers": (None, ["template_id", "slot_name", "word_id"]),
    "learning_order": ("step", ["step", "item_type", "item_id", "why"]),
    "word_units": (None, ["word_id", "syl_index", "position", "unit_id"]),
    "word_categories": ("word_id", ["word_id", "categories"]),
    "sentence_slots": (None, ["sentence_id", "position", "accepts", "exclude_word_ids"]),
}
CAT_RE = re.compile(r"^[a-z][a-z_]*$")
FUNCTION, ACTION = "function", "action"
CONFIDENCE = {"verified", "derived", "unverified"}
TONES = {"low-rising", "high-rising", "mid", "low-falling", "high-falling"}
TIERS = {"30", "100", "300", "600", "extra"}
CLASSIFIER_TYPES = {"specific", "self", "measure", "none"}
ID_FORMATS = {"words": re.compile(r"^W\d{6}$"), "sentences": re.compile(r"^S\d{9}$")}
LAO_RE = re.compile(r"^[຀-໿\s|?!.,()«»\"'\-◌_…]*$")
PUNCT_RE = re.compile(r"[?!.,()«»\"'…]")
HARD_CAP, TARGET = 3000, 600  # cap: user decision 2026-10-10; TARGET = letter/vowel coverage word

errors, warnings = [], []


def err(msg):
    errors.append(msg)


def warn(msg, kind=None):
    warnings.append((kind or msg, msg))


def load(data_dir, name):
    path = os.path.join(data_dir, name + ".csv")
    if not os.path.exists(path):
        warn(f"{name}.csv missing (skipped)")
        return None, []
    with open(path, encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)
        cols = reader.fieldnames or []
    id_col, required = TABLES[name]
    for c in required + COMMON:
        if c not in cols:
            err(f"{name}.csv: missing column '{c}'")
    if id_col:
        seen = set()
        for i, r in enumerate(rows, 2):
            v = r.get(id_col, "")
            if not v:
                err(f"{name}.csv line {i}: empty {id_col}")
            elif v in seen:
                err(f"{name}.csv line {i}: duplicate {id_col} {v}")
            elif name in ID_FORMATS and not ID_FORMATS[name].match(v):
                err(f"{name}.csv line {i}: {id_col} '{v}' does not match {ID_FORMATS[name].pattern}")
            seen.add(v)
    for i, r in enumerate(rows, 2):
        if r.get("confidence", "") not in CONFIDENCE:
            err(f"{name}.csv line {i}: confidence '{r.get('confidence', '')}' not in {sorted(CONFIDENCE)}")
        if not r.get("source", "") and r.get("confidence") != "unverified":
            err(f"{name}.csv line {i}: no source but confidence is {r.get('confidence')}")
    return rows, list(cols)


def ids(rows, col):
    return {r[col] for r in rows} if rows else set()


def split_ids(v):
    return [x.strip() for x in (v or "").split("|") if x.strip()]


def check_lao(name, rows, cols):
    for i, r in enumerate(rows or [], 2):
        for c in cols:
            v = r.get(c, "")
            if v and not LAO_RE.match(v):
                bad = sorted({ch for ch in v if not LAO_RE.match(ch)})
                err(f"{name}.csv line {i}: {c} has non-Lao characters {bad}")


def is_noun(r):
    return any(p.strip().startswith("noun") or p.strip() == "proper noun"
               for p in (r.get("pos") or "").split(";"))


def check_classifiers(words, words_by_id, has_cols):
    """Classifier rules from SCHEMA.md 'Classifiers'."""
    nouns = [r for r in words if is_noun(r)]
    if not has_cols:
        warn(f"words.csv has no classifier_type/classifier_confidence columns yet ({len(nouns)} nouns to classify)")
        return
    for r in words:
        wid, ct = r["word_id"], (r.get("classifier_type") or "").strip()
        cw = (r.get("classifier_word_id") or "").strip()
        cc = (r.get("classifier_confidence") or "").strip()
        if not is_noun(r):
            if ct or cc:
                err(f"words {wid}: classifier_type/confidence set on a non-noun (pos '{r.get('pos')}')")
            continue
        if not ct:
            err(f"words {wid}: noun without classifier_type")
            continue
        if ct not in CLASSIFIER_TYPES:
            err(f"words {wid}: classifier_type '{ct}' not in {sorted(CLASSIFIER_TYPES)}")
            continue
        if cc not in CONFIDENCE:
            err(f"words {wid}: classifier_confidence '{cc}' not in {sorted(CONFIDENCE)}")
        if ct == "self" and cw != wid:
            err(f"words {wid}: classifier_type self but classifier_word_id is '{cw}' (must be {wid})")
        elif ct == "none" and cw:
            err(f"words {wid}: classifier_type none but classifier_word_id is {cw}")
        elif ct == "specific":
            if not cw:
                warn(f"words {wid}: specific classifier not yet a word in words.csv", "specific classifier missing")
            elif cw == wid:
                err(f"words {wid}: classifier_type specific points to itself (use self)")
            elif "classifier" not in (words_by_id.get(cw, {}).get("pos") or ""):
                warn(f"words {wid}: classifier {cw} does not have pos 'classifier'", "classifier word pos")
        if cc == "verified" and "Classifier:" not in (r.get("notes") or ""):
            warn(f"words {wid}: verified classifier without a 'Classifier:' source note", "classifier source note")


def load_categories(data_dir):
    """The closed category set from categories.csv, or None when the file does not exist."""
    path = os.path.join(data_dir, "categories.csv")
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)
        cols = reader.fieldnames or []
    for c in ("category", "definition", "examples"):
        if c not in cols:
            err(f"categories.csv: missing column '{c}'")
    seen = set()
    for i, r in enumerate(rows, 2):
        if None in r:
            err(f"categories.csv line {i}: more fields than the header (unquoted comma?)")
        c = (r.get("category") or "").strip()
        if not CAT_RE.match(c):
            err(f"categories.csv line {i}: category '{c}' must be lower case letters and _")
        elif c in seen:
            err(f"categories.csv line {i}: duplicate category {c}")
        elif not (r.get("definition") or "").strip():
            warn(f"categories.csv line {i}: {c} has no definition", "category without definition")
        seen.add(c)
    for need in (FUNCTION, ACTION):
        if need not in seen:
            warn(f"categories.csv: no '{need}' category (DESIGN first set)")
    return seen


def check_activity_data(t, cats, word_ids, sentence_ids):
    """word_categories, sentence_slots, word_units (PLAN S7c)."""
    wc, ss, wu, sw = t["word_categories"], t["sentence_slots"], t["word_units"], t["sentence_words"]
    if (wc or ss) and cats is None:
        err("word_categories.csv / sentence_slots.csv have rows but data/categories.csv is missing")
    allowed = cats or set()
    own = {}
    for i, r in enumerate(wc or [], 2):
        wid = r["word_id"]
        if wid not in word_ids:
            err(f"word_categories line {i}: word {wid} not in words")
        cs = split_ids(r.get("categories"))
        if not cs:
            err(f"word_categories line {i}: {wid} has no categories")
        bad = [c for c in cs if c not in allowed]
        if bad and cats is not None:
            err(f"word_categories line {i}: {wid} categories {bad} not in categories.csv")
        if len(set(cs)) != len(cs):
            warn(f"word_categories line {i}: {wid} lists a category twice", "category listed twice")
        own[wid] = set(cs)
    pos_word = {}
    for r in sw or []:
        if (r.get("position") or "").strip().isdigit():
            pos_word[(r["sentence_id"], int(r["position"]))] = r["word_id"]
    seen = set()
    for i, r in enumerate(ss or [], 2):
        sid, pos = r["sentence_id"], (r.get("position") or "").strip()
        ctx = f"sentence_slots line {i} ({sid}/{pos})"
        if sid not in sentence_ids:
            err(f"{ctx}: sentence not in sentences")
            continue
        if not pos.isdigit():
            err(f"{ctx}: position must be a number")
            continue
        if (sid, pos) in seen:
            err(f"{ctx}: duplicate slot")
        seen.add((sid, pos))
        acc = split_ids(r.get("accepts"))
        if not acc:
            err(f"{ctx}: accepts is empty")
        bad = [c for c in acc if c not in allowed]
        if bad and cats is not None:
            err(f"{ctx}: accepts {bad} not in categories.csv")
        for x in split_ids(r.get("exclude_word_ids")):
            if x not in word_ids:
                err(f"{ctx}: exclude_word_ids {x} not in words")
        ans = pos_word.get((sid, int(pos)))
        if not ans:
            err(f"{ctx}: the sentence has no word at position {pos} (sentence_words)")
        elif ans not in own:
            err(f"{ctx}: answer word {ans} has no word_categories row")
        elif acc and not own[ans] & set(acc):
            err(f"{ctx}: answer word {ans} ({'|'.join(sorted(own[ans]))}) fits none of accepts {'|'.join(acc)}")
    for i, r in enumerate(wu or [], 2):
        if r["word_id"] not in word_ids:
            err(f"word_units line {i}: word {r['word_id']} not in words")
        if not (r.get("unit_id") or "").strip():
            err(f"word_units line {i}: empty unit_id")


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("data_dir", nargs="?", default="data")
    ap.add_argument("--quiet", action="store_true", help="group warnings by kind (count + 5 examples)")
    a = ap.parse_args()
    loaded = {n: load(a.data_dir, n) for n in TABLES}
    t = {n: v[0] for n, v in loaded.items()}
    letters, vowels, words = t["letters"], t["vowels"], t["words"]
    sentences, sw, templates, tf = t["sentences"], t["sentence_words"], t["templates"], t["template_fillers"]
    word_ids = ids(words, "word_id")
    letter_ids = ids(letters, "letter_id")
    vowel_ids = ids(vowels, "vowel_id")
    sentence_ids = ids(sentences, "sentence_id")
    template_ids = ids(templates, "template_id")

    check_lao("letters", letters, ["lao", "name_lao"])
    check_lao("vowels", vowels, ["lao_pattern"])
    check_lao("words", words, ["lao", "syllables"])
    check_lao("sentences", sentences, ["lao", "lao_spaced"])

    words_by_id = {r["word_id"]: r for r in words or []}
    if words is not None:
        if len(words) > HARD_CAP:
            err(f"words.csv: {len(words)} words exceeds the hard cap of {HARD_CAP}")
        for i, r in enumerate(words, 2):
            wid = r["word_id"]
            syl = split_ids(r.get("syllables"))
            if "".join(syl) != r.get("lao", ""):
                err(f"words {wid}: syllables '{r.get('syllables')}' do not join to '{r.get('lao')}'")
            tones = split_ids(r.get("tone_by_syllable"))
            if tones:
                if len(tones) != len(syl):
                    err(f"words {wid}: {len(tones)} tones for {len(syl)} syllables")
                for tn in tones:
                    if tn not in TONES:
                        err(f"words {wid}: unknown tone '{tn}'")
            else:
                warn(f"words {wid}: no tone_by_syllable", "no tone_by_syllable")
            if r.get("tier") and r["tier"] not in TIERS:
                err(f"words {wid}: tier '{r['tier']}' not in {sorted(TIERS)}")
            if r.get("classifier_word_id") and r["classifier_word_id"] not in word_ids:
                err(f"words {wid}: classifier_word_id {r['classifier_word_id']} not in words")
            for c in split_ids(r.get("component_word_ids")):
                if c not in word_ids:
                    err(f"words {wid}: component {c} not in words")
                elif int(words_by_id[c].get("intro_order") or 0) > int(r.get("intro_order") or 0):
                    warn(f"words {wid}: component {c} is introduced after the compound", "component after compound")
            for c in split_ids(r.get("new_letter_ids")):
                if c not in letter_ids:
                    err(f"words {wid}: new_letter_id {c} not in letters")
            for c in split_ids(r.get("new_vowel_ids")):
                if c not in vowel_ids:
                    err(f"words {wid}: new_vowel_id {c} not in vowels")
        orders = [r.get("intro_order") for r in words if r.get("intro_order")]
        if len(orders) != len(set(orders)):
            err("words.csv: duplicate intro_order values")
        wcols = loaded["words"][1]
        check_classifiers(words, words_by_id, "classifier_type" in wcols and "classifier_confidence" in wcols)

    if sentences is not None:
        sw_by_sentence = {}
        for r in sw or []:
            sw_by_sentence.setdefault(r["sentence_id"], []).append(r)
        for r in sentences:
            sid = r["sentence_id"]
            if r.get("target_word_id") and r["target_word_id"] not in word_ids:
                err(f"sentences {sid}: target_word_id {r['target_word_id']} not in words")
            if r.get("template_id") and r["template_id"] not in template_ids:
                err(f"sentences {sid}: template_id {r['template_id']} not in templates")
            spaced = PUNCT_RE.sub("", r.get("lao_spaced", ""))
            plain = PUNCT_RE.sub("", r.get("lao", ""))
            if spaced.replace(" ", "") != plain.replace(" ", ""):
                err(f"sentences {sid}: lao_spaced does not match lao")
            toks = spaced.split()
            parts = sorted(sw_by_sentence.get(sid, []), key=lambda x: int(x["position"] or 0))
            if sw is not None:
                lao_parts = [words_by_id.get(p["word_id"], {}).get("lao", "?") for p in parts]
                if lao_parts != toks:
                    err(f"sentences {sid}: sentence_words {lao_parts} != lao_spaced tokens {toks}")
    for r in sw or []:
        if r["sentence_id"] not in sentence_ids:
            err(f"sentence_words: sentence {r['sentence_id']} not in sentences")
        if r["word_id"] not in word_ids:
            err(f"sentence_words: word {r['word_id']} not in words")
    for r in tf or []:
        if r["template_id"] not in template_ids:
            err(f"template_fillers: template {r['template_id']} not in templates")
        if r["word_id"] not in word_ids:
            err(f"template_fillers: word {r['word_id']} not in words")
    cats = load_categories(a.data_dir)
    check_activity_data(t, cats, word_ids, sentence_ids)

    if words is not None and sw is not None:
        uses = {}
        for r in sw:
            uses.setdefault(r["word_id"], set()).add(r["sentence_id"])
        thin = [w for w in word_ids if len(uses.get(w, ())) < 2]
        if thin:
            warn(f"{len(thin)} words appear in fewer than 2 sentences: {sorted(thin)[:20]}{' ...' if len(thin) > 20 else ''}")

    # Coverage
    def intro_ok(row, table, pattern_col):
        wid = row.get("intro_word_id")
        if not wid:
            return "not introduced"
        w = words_by_id.get(wid)
        if not w:
            return f"intro_word_id {wid} not in words"
        if int(w.get("intro_order") or 0) > TARGET:
            return f"introduced at word {w.get('intro_order')} (> {TARGET})"
        needed = [ch for ch in row[pattern_col] if ch != "◌"]
        if any(ch not in w.get("lao", "") for ch in needed):
            return f"intro word {wid} {w.get('lao')} does not contain {row[pattern_col]}"
        return ""

    for name, rows, col, idc in (("letters", letters, "lao", "letter_id"), ("vowels", vowels, "lao_pattern", "vowel_id")):
        if rows is None:
            continue
        for r in rows:
            req = r.get("coverage_required")
            if req in ("yes", "reading-only"):
                problem = intro_ok(r, name, col)
                if problem and words is not None and len(words) >= TARGET and req == "yes":
                    err(f"{name} {r[idc]} {r[col]}: {problem}")
                elif problem and "does not contain" in problem:
                    err(f"{name} {r[idc]} {r[col]}: {problem}")

    print("== Counts ==")
    if letters is not None:
        kinds = {}
        for r in letters:
            kinds[r["kind"]] = kinds.get(r["kind"], 0) + 1
        print("letters by kind:", kinds)
    if vowels is not None:
        print("vowel written forms:", len(vowels), "| sound groups:", len({r.get('sound_group') for r in vowels}))
    for name in ("letters", "vowels"):
        rows = t[name]
        if rows is not None:
            need = [r for r in rows if r.get("coverage_required") == "yes"]
            done = [r for r in need if r.get("intro_word_id")]
            print(f"{name} coverage (required=yes): {len(done)}/{len(need)} introduced")
    if words is not None:
        conf, tiers, ctypes, cconf = {}, {}, {}, {}
        for r in words:
            conf[r["confidence"]] = conf.get(r["confidence"], 0) + 1
            tiers[r.get("tier", "")] = tiers.get(r.get("tier", ""), 0) + 1
            if is_noun(r):
                ct, cc = r.get("classifier_type", ""), r.get("classifier_confidence", "")
                ctypes[ct] = ctypes.get(ct, 0) + 1
                cconf[cc] = cconf.get(cc, 0) + 1
        print(f"words: {len(words)} (cap {HARD_CAP}) | confidence {conf} | tiers {tiers}")
        print(f"nouns: {sum(ctypes.values())} | classifier_type {ctypes} | classifier_confidence {cconf}")
    if sentences is not None:
        conf = {}
        for r in sentences:
            conf[r["confidence"]] = conf.get(r["confidence"], 0) + 1
        print(f"sentences: {len(sentences)} | confidence {conf}")
    print(f"activity data: categories {len(cats) if cats is not None else 'missing'} | "
          f"word_categories {len(t['word_categories'] or [])} | sentence_slots {len(t['sentence_slots'] or [])} | "
          f"word_units {len(t['word_units'] or [])}")
    print(f"\n== {len(errors)} ERROR(S) ==")
    for e in errors:
        print("ERROR", e)
    print(f"\n== {len(warnings)} WARNING(S) ==")
    if a.quiet:
        groups = {}
        for kind, msg in warnings:
            groups.setdefault(kind, []).append(msg)
        for kind, msgs in groups.items():
            if len(msgs) == 1:
                print("WARN ", msgs[0])
            else:
                print(f"WARN  {kind}: {len(msgs)} (e.g. {'; '.join(msgs[:5])})")
    else:
        for _, msg in warnings:
            print("WARN ", msg)
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
